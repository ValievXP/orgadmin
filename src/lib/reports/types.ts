/** Числовой формат ячейки Excel. Строковые ячейки формат игнорируют. */
export type NumFmt =
  | 'integer'    // 1 234
  | 'decimal'    // 1 234,5
  | 'percent'    // 85,3 %
  | 'text';      // как есть

export interface ReportColumn<Row> {
  /** Заголовок колонки в выгрузке (по-русски, как в UI) */
  header: string;
  /** Ширина колонки в символах. Если не задана — считается по заголовку */
  width?: number;
  /** Значение ячейки. index — порядковый номер строки с 0 */
  value: (row: Row, index: number) => string | number | null | undefined;
  /** Формат числа; для строковых значений не применяется */
  format?: NumFmt;
}

/** Пара «показатель — значение» для блока итогов под таблицей. */
export type SummaryRow = [label: string, value: string | number];

export interface ReportTemplate<Row> {
  /** Технический id блока — используется в имени файла */
  id: string;
  /** Заголовок отчёта, попадает в шапку листа */
  title: string;
  /** Имя листа в книге. Excel ограничивает 31 символом — движок обрежет */
  sheetName: string;
  /** Пояснение под заголовком: что именно за данные */
  description?: string;
  columns: ReportColumn<Row>[];
  /** Блок «Итого» под таблицей */
  summary?: (rows: Row[], ctx: ReportContext) => SummaryRow[];
  /** Скрыть счётчик записей в шапке: для сводок он бессмыслен */
  hideRowCount?: boolean;
}

/**
 * Снимок состояния фильтров на момент выгрузки.
 * Попадает в шапку каждого листа, чтобы отчёт можно было читать
 * отдельно от интерфейса и понимать, по какому срезу он собран.
 */
export interface ReportContext {
  /** Начало глобального периода, как показано в UI */
  periodStart?: string;
  periodEnd?: string;
  /** Активные фильтры: подпись → выбранные значения */
  filters?: Record<string, string[] | string | undefined>;
  /** Дата формирования; передаётся снаружи, чтобы модуль оставался чистым */
  generatedAt: string;
  /** Дата для имени файла в виде ГГГГ-ММ-ДД — чтобы выгрузки не перезаписывали друг друга */
  fileStamp?: string;
}

/** Готовый к записи лист: шаблон + данные под него. */
export interface ReportSheet<Row = any> {
  template: ReportTemplate<Row>;
  rows: Row[];
}
